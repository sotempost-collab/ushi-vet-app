// Структурированные данные осмотра по системам.
// Для каждого параметра:
//   - description — что и как оценивается (методика)
//   - normalBySpecies — видоспецифичная норма (dog / cat / other)
//   - normalRange — универсальная норма-фолбэк
//   - deviationOptions — массив { value, description } — варианты отклонений с пояснением

export interface DeviationOption {
  value: string // краткое название (для селекта)
  description: string // клиническое описание показателя при отклонении
}

export interface ExaminationParam {
  id: string
  name: string
  unit?: string
  description: string // что оценивается и как
  normalBySpecies: {
    dog?: string
    cat?: string
    other?: string
  }
  normalRange: string // универсальный фолбэк
  deviationOptions: DeviationOption[]
}

export interface ExaminationSystem {
  id: string
  name: string
  icon: string
  description?: string
  params: ExaminationParam[]
}

// Хелпер: получить норму для вида
export function getNormalForSpecies(
  param: ExaminationParam,
  species: 'dog' | 'cat' | 'other'
): string {
  return param.normalBySpecies[species] || param.normalRange
}

